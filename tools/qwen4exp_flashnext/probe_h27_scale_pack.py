"""H27 isolated hardware probe: four-row packed E4M3 scale decode.

H27 wants ONE ``v_convert_f8_to_bf16_all_b`` to decode the 32 E4M3 scale bytes
of FOUR weight rows (one row per 64-byte dual group) instead of one row per
call. That rests on three measured facts and one new instruction sequence:

  (a) ``convert.f8_143`` without ``SW_LINEAR`` maps ``pair.v1`` lane i to
      source byte 2i and ``pair.v2`` lane i to source byte 2i+1 (H21 probe,
      all 256 source bytes) -- so the 128 lanes of ``pair.v1`` cover the whole
      256-byte input and four 32-byte slots, one per dual group, land in four
      consecutive 32-lane blocks.
  (b) ``v_u8_shuffle_b`` reads the source's SAME dual group as the output byte
      (H19 probe, 100 % of lanes), so a per-dual-group byte spread can read the
      low 32 bytes of every dual group independently.
  (c) ``v_u8_mov_dual_group_b`` (the merging form of ``mov_dg``) moves a whole
      source dual group into a chosen destination dual group while keeping the
      fallback operand's other groups, which is how the four rows' scale bytes
      (each row's in dual group 0 of its own 256-byte load) are packed into
      dual groups 0..3 with three instructions.

This probe builds a variant library from a copy of ``vllm-gaudi/csrc/qwen4exp``
(production tree untouched, exactly like ``probe_h21_convert_f8.py``),
replaces the indexed-dequant kernel with a dump kernel, and checks the four-row
decode lane by lane against the IEEE E4M3 (bias 7, e4m3fn) reference that
``nvfp4_e4m3_vec_bits`` implements -- including the exp == 15 codes
(0x78..0x7E, 0xF8..0xFE) that need the H21 bias fix.

Run (card must be free):
  PT_HPU_LAZY_MODE=0 .venv/bin/python tools/qwen4exp_flashnext/probe_h27_scale_pack.py
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
CSRC = REPO / "vllm-gaudi/csrc/qwen4exp"
EXT = next((CSRC / "pytorch").glob("hpu_qwen4exp_nvfp4_dequant_pt2*.so"), None)
WORK = Path("/tmp/h27")
PROBE_BUILD = WORK / "probe_build"

PROBE_KERNEL = """// SPDX-License-Identifier: Apache-2.0
// H27 probe kernel (isolated hardware probe, NOT a production kernel).
// Generated by tools/qwen4exp_flashnext/probe_h27_scale_pack.py.
//
// Reuses the indexed-dequant op signature so no new host glue is needed:
// `packed` only supplies the geometry (4 rows, K/2 = 256), `scales` is a
// [E, 4, 32] E4M3 plane whose rows 0..3 are the four rows packed into one
// decode, and every output row is a 128-lane dump:
//   row 0  the four-row decode      (row r in lanes 32r..32r+31)
//   row 1  the packed scale register (bytes, read back as uint8)
//   row 2  raw load of scale row 0   (bytes)
//   row 3  the spread register       (bytes)
#include "qwen4exp_nvfp4_common.h"

void main(tensor expert_ids, tensor packed, tensor scales, tensor scale2, tensor output)
{
    const uchar256 q0 = v_u8_ld_tnsr_b((int5){0, 0, 0, 0, 0}, scales);
    const uchar256 q1 = v_u8_ld_tnsr_b((int5){0, 1, 0, 0, 0}, scales);
    const uchar256 q2 = v_u8_ld_tnsr_b((int5){0, 2, 0, 0, 0}, scales);
    const uchar256 q3 = v_u8_ld_tnsr_b((int5){0, 3, 0, 0, 0}, scales);
    const uchar256 spread_idx = nvfp4_e4m3_spread_index_packed();
    const uchar256 packed_scale = nvfp4_pack_scale_rows(q0, q1, q2, q3);
    const ushort128 bits = nvfp4_e4m3_vec_bits_packed(packed_scale, spread_idx);
    const uchar256 spread = v_u8_shuffle_b(packed_scale, spread_idx, 0, (uchar256){0});
    v_bf16_st_tnsr((int5){0, 0, 0, 0, 0}, output, *((bfloat128*)&bits));
    v_bf16_st_tnsr((int5){0, 1, 0, 0, 0}, output, *((bfloat128*)&packed_scale));
    v_bf16_st_tnsr((int5){0, 2, 0, 0, 0}, output, *((bfloat128*)&q0));
    v_bf16_st_tnsr((int5){0, 3, 0, 0, 0}, output, *((bfloat128*)&spread));
}
"""

# The e == 0 magnitude table of the old integer decode (m -> BF16 bits, bias 7),
# identical to probe_h21_convert_f8.py.
E4M3_SUB = {0: 0, 1: 118 << 7, 2: 119 << 7, 3: (119 << 7) | 64, 4: 120 << 7,
            5: (120 << 7) | 32, 6: (120 << 7) | 64, 7: (120 << 7) | 96}


def e4m3_bits(code: int) -> int:
    e = (code >> 3) & 15
    m = code & 7
    sign = (code & 0x80) << 8
    if e == 0:
        return sign | E4M3_SUB[m]
    return sign | (((e + 120) << 7) | (m << 4))


def build_probe_library() -> Path:
    src = WORK / "probe_src"
    if src.exists():
        shutil.rmtree(src)
    shutil.copytree(CSRC, src, ignore=shutil.ignore_patterns("build", "*.so", "*.o"))
    (src / "kernels" / "qwen4exp_nvfp4_indexed_dequant_bf16_gaudi2.c").write_text(PROBE_KERNEL)
    PROBE_BUILD.mkdir(parents=True, exist_ok=True)
    subprocess.run(["cmake", str(src)], cwd=PROBE_BUILD, check=True,
                   stdout=subprocess.DEVNULL)
    subprocess.run(["make", "-j8"], cwd=PROBE_BUILD, check=True,
                   stdout=subprocess.DEVNULL)
    so = PROBE_BUILD / "libqwen4exp_gaudi2_kernels.so"
    assert so.is_file(), f"probe library missing: {so}"
    return so


def main() -> int:
    if EXT is None:
        raise SystemExit("build the pytorch extension first (pytorch/setup.py)")
    so = Path(sys.argv[1]) if len(sys.argv) > 1 else build_probe_library()
    print(f"probe_h27_scale_pack: kernel={so}")
    os.environ["GC_KERNEL_PATH"] = str(so.resolve())
    os.environ.setdefault("PT_HPU_LAZY_MODE", "0")

    import torch  # noqa: E402
    import habana_frameworks.torch.core  # noqa: F401, E402

    torch.ops.load_library(str(EXT))
    op = torch.ops.custom_op.custom_qwen4exp_nvfp4_indexed_dequant_bf16_gaudi2

    # 32 distinct codes per row + the exp == 15 range at fixed slots, so the
    # bias fix is exercised through the packed path too.
    rows, per_row = 4, 32
    codes = np.zeros((rows, per_row), dtype=np.uint8)
    for r in range(rows):
        codes[r] = (0x08 + (r * per_row + np.arange(per_row)) % 0x70).astype(np.uint8)
    codes[0, [3, 11, 19, 27]] = [0x78, 0x7C, 0x7E, 0x88]     # exp==15 + -0.0
    codes[1, [5, 13]] = [0xF8, 0xFE]                         # negative exp==15
    codes[2, [0, 31]] = [0x00, 0x80]                         # +0 / -0
    codes[3, [7, 15, 23]] = [0x01, 0x07, 0x38]               # subnormals + 1.0

    # packed is only geometry: [E=1, N=4, K/2=256] -> K=512, N=4.
    packed = torch.zeros((1, rows, 256), dtype=torch.uint8, device="hpu")
    # A 256-byte scale load from row r reads 8 rows of the plane; make every
    # byte of the window a known value (0x38 = 1.0 elsewhere) so the dump of
    # the packed register is interpretable.
    plane = np.full((1, rows, per_row), 0x38, dtype=np.uint8)
    plane[0, :, :] = codes
    scales = torch.from_numpy(plane).to("hpu")
    ids = torch.zeros(1, dtype=torch.int32, device="hpu")
    scale2 = torch.ones(1, dtype=torch.float32, device="hpu")

    out = op(ids, packed, scales, scale2)
    torch.hpu.synchronize()
    got = out.cpu().view(torch.uint16).numpy()[0]      # [4, 512] uint16 lanes
    raw = out.cpu().view(torch.uint8).numpy()[0]       # [4, 1024] bytes

    # ---- (1) the four-row decode, lane by lane ---------------------------
    want = np.array([[e4m3_bits(int(codes[r, c])) for c in range(per_row)]
                     for r in range(rows)], dtype=np.uint16)
    decoded = got[0][:128]
    bad = []
    for lane in range(128):
        r, c = lane // per_row, lane % per_row
        if int(decoded[lane]) != int(want[r, c]):
            bad.append((lane, r, c, int(decoded[lane]), int(want[r, c])))
    print(f"(1) four-row decode: {128 - len(bad)}/128 lanes bit-identical")
    for lane, r, c, g, w in bad[:12]:
        print(f"    lane {lane:3d} (row {r} scale {c}): got 0x{g:04x} want 0x{w:04x}")
    # pair.v2 must be the same values (odd byte of each u16 lane).
    if decoded.size == 128 and bad == []:
        print("    (pair.v1 lanes 0..31/32..63/64..95/96..127 = rows 0/1/2/3)")

    # ---- (2) the packed register: dg r bytes 0..31 = row r's scales ------
    pack_bytes = raw[1]                                # 1024 bytes = 4 dual groups
    pack_ok = 0
    for r in range(rows):
        for c in range(per_row):
            pack_ok += int(pack_bytes[r * 64 + c] == codes[r, c])
    print(f"(2) packed register: {pack_ok}/128 (row, scale) bytes at dg r offset c")
    print(f"    dg0[0:8]  = {[hex(int(v)) for v in pack_bytes[0:8]]}")
    print(f"    dg1[0:8]  = {[hex(int(v)) for v in pack_bytes[64:72]]}")
    print(f"    dg2[0:8]  = {[hex(int(v)) for v in pack_bytes[128:136]]}")
    print(f"    dg3[0:8]  = {[hex(int(v)) for v in pack_bytes[192:200]]}")

    # ---- (3) the load content: q0 dg0 = row 0's 32 scale bytes -----------
    q0 = raw[2]
    q0_ok = sum(int(q0[c]) == int(codes[0, c]) for c in range(per_row))
    print(f"(3) scale load row 0: {q0_ok}/32 first bytes match")
    print(f"    q0[0:8]   = {[hex(int(v)) for v in q0[0:8]]}"
          f"  (dg0[32:40] = {[hex(int(v)) for v in q0[32:40]]})")

    # ---- (4) the spread: byte b of every dg = raw byte (b>>1)&0x1f ------
    spread = raw[3]
    spread_ok = 0
    for b in range(256):
        dg, off = b // 64, b % 64
        src = dg * 64 + ((off >> 1) & 0x1F)
        spread_ok += int(spread[b] == pack_bytes[src])
    print(f"(4) spread pattern: {spread_ok}/256 bytes == raw dg byte ((b>>1)&0x1f)")

    ok = not bad and pack_ok == 128 and q0_ok == per_row and spread_ok == 256
    print("\nverdict:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
