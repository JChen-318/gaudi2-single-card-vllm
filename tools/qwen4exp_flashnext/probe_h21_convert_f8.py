"""H21 isolated hardware probe: ``v_convert_f8_to_bf16_all_b`` on Gaudi2.

H19 left one lead: E4M3 scale decode (~21 vector instructions per row per tile)
should collapse to the hardware ``convert.f8_143`` conversion. H19 tried it with
``SW_FP8_BIAS7 | SW_LINEAR``, got NaN output and shelved the lead. This probe
answers the two questions that decision needs, on the device, with no
production kernel in the loop:

(a) **Lane mapping.** ``v_convert_f8_to_bf16_all_b(uchar256, flags)`` returns a
    ``bfloat128_pair_t`` (two V registers). Which source byte index ``0..255``
    lands in which lane ``0..127`` of ``pair.v1`` / ``pair.v2``? Measured with a
    one-hot byte pattern per source index (``0x38`` = E4M3 1.0, everything else
    ``0x00`` = 0.0) for four flag combinations:

      row 0  SW_FP8_BIAS7
      row 1  SW_FP8_BIAS7 | SW_LINEAR
      row 2  SW_FP8_BIAS7 | SW_FP8_143_INF_NAN_MODE_0
      row 3  SW_FP8_BIAS7 | SW_FP8_143_INF_NAN_MODE_0 | SW_LINEAR

(b) **All 128 codes 0x00..0x7F bit-for-bit** against the IEEE E4M3 (bias 7,
    e4m3fn) reference that ``nvfp4_e4m3_vec_bits`` implements: normals
    ``2^(e-7) * (1 + m/8)``, subnormals ``m * 2^-9``, and the exp==15 codes
    0x78..0x7E = 256, 288, ... 448 (0x7F is the NaN code and is reported
    separately). Both the IEEE BF16 bits and the softfloat value are printed,
    so a lane that only differs by which real number it decodes to is
    distinguishable from a lane that returns Inf/NaN.

The probe kernel (``PROBE_KERNEL``) reuses the shipped indexed-dequant op
signature/glue so no new host op is required: ``packed`` supplies the 256 raw
bytes, ``scales``/``scale2`` and the index space are ignored, and the four rows
of the ``[1, 4, 512]`` BF16 output carry the four flag combinations.

The variant library is built into ``/tmp/h21/probe_build`` from a copy of
``vllm-gaudi/csrc/qwen4exp`` (production tree untouched), exactly like
``probe_h19_dual_group.py`` did for H19.

Run (card must be free):
  PT_HPU_LAZY_MODE=0 .venv/bin/python tools/qwen4exp_flashnext/probe_h21_convert_f8.py
  # or against a prebuilt probe library:
  PT_HPU_LAZY_MODE=0 .venv/bin/python tools/qwen4exp_flashnext/probe_h21_convert_f8.py <so>
"""
from __future__ import annotations

import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
CSRC = REPO / "vllm-gaudi/csrc/qwen4exp"
EXT = next((CSRC / "pytorch").glob("hpu_qwen4exp_nvfp4_dequant_pt2*.so"), None)
WORK = Path("/tmp/h21")
PROBE_BUILD = WORK / "probe_build"
TPC_COMPILER = "/usr/bin/tpc-clang"
TPC_INCLUDE = "/usr/lib/habanatools/include"

FLAG_SETS = (
    ("BIAS7", "SW_FP8_BIAS7"),
    ("BIAS7|LINEAR", "SW_FP8_BIAS7 | SW_LINEAR"),
    ("BIAS15", "SW_FP8_BIAS15"),
    ("BIAS15|LINEAR", "SW_FP8_BIAS15 | SW_LINEAR"),
    ("BIAS11", "SW_FP8_BIAS11"),
    ("BIAS7|MODE0", "SW_FP8_BIAS7 | SW_FP8_143_INF_NAN_MODE_0"),
)

PROBE_KERNEL = """// SPDX-License-Identifier: Apache-2.0
// H21 probe kernel (isolated hardware probe, NOT a production kernel).
// Generated by tools/qwen4exp_flashnext/probe_h21_convert_f8.py.
//
// Converts 256 raw `packed` bytes with four v_convert_f8_to_bf16_all_b flag
// combinations and stores both halves of the returned pair into output rows:
//   row r, [0..127]   = pair.v1
//   row r, [128..255] = pair.v2
typedef _Float8_143 f8v256 __attribute__((ext_vector_type(256)));

void main(tensor expert_ids, tensor packed, tensor scales, tensor scale2, tensor output)
{
    const uchar256 src = v_u8_ld_tnsr_b((int5){0, 0, 0, 0, 0}, packed);
    const f8v256 f = *((f8v256*)&src);
%(converts)s
%(stores)s}
"""


def build_probe_library() -> Path:
    """Compile the probe kernel into a variant library under /tmp/h21."""
    src = WORK / "probe_src"
    if src.exists():
        shutil.rmtree(src)
    shutil.copytree(CSRC, src, ignore=shutil.ignore_patterns("build", "*.so", "*.o"))
    converts, stores = [], []
    for row, (_, flags) in enumerate(FLAG_SETS):
        converts.append(
            f"    const bfloat128_pair_t p{row} = "
            f"v_convert_f8_to_bf16_all_b(f, {flags});")
        stores.append(
            f"    v_bf16_st_tnsr((int5){{0, {row}, 0, 0, 0}}, output, p{row}.v1);")
        stores.append(
            f"    v_bf16_st_tnsr((int5){{128, {row}, 0, 0, 0}}, output, p{row}.v2);")
    (src / "kernels" / "qwen4exp_nvfp4_indexed_dequant_bf16_gaudi2.c").write_text(
        PROBE_KERNEL % {"converts": "\n".join(converts), "stores": "\n".join(stores)})
    PROBE_BUILD.mkdir(parents=True, exist_ok=True)
    subprocess.run(["cmake", str(src)], cwd=PROBE_BUILD, check=True,
                   stdout=subprocess.DEVNULL)
    subprocess.run(["make", "-j8"], cwd=PROBE_BUILD, check=True,
                   stdout=subprocess.DEVNULL)
    so = PROBE_BUILD / "libqwen4exp_gaudi2_kernels.so"
    assert so.is_file(), f"probe library missing: {so}"
    return so


# ---------------------------------------------------------------------------
# IEEE E4M3 (bias 7, e4m3fn) -> BF16, the reference nvfp4_e4m3_vec_bits builds
# ---------------------------------------------------------------------------

# The e == 0 magnitude table of nvfp4_e4_sub_table (m -> BF16 bits, bias 7).
E4M3_SUB = {0: 0, 1: 118 << 7, 2: 119 << 7, 3: (119 << 7) | 64, 4: 120 << 7,
            5: (120 << 7) | 32, 6: (120 << 7) | 64, 7: (120 << 7) | 96}


def e4m3_bits(code: int) -> int:
    """BF16 bits of E4M3 code `code`; exactly what nvfp4_e4m3_vec_bits builds."""
    e = (code >> 3) & 15
    m = code & 7
    sign = (code & 0x80) << 8
    if e == 0:
        return sign | E4M3_SUB[m]
    return sign | (((e + 120) << 7) | (m << 4))


def e4m3_value(code: int) -> float:
    """Softfloat value of E4M3 code `code` (bias 7, e4m3fn)."""
    e = (code >> 3) & 15
    m = code & 7
    sign = -1.0 if code & 0x80 else 1.0
    if e == 0:
        return sign * m * 2.0**-9
    return sign * 2.0 ** (e - 7) * (1.0 + m / 8.0)


def bits_to_float(bits: int) -> float:
    return struct.unpack("<f", struct.pack("<I", bits << 16))[0]


def bits_to_str(bits: int) -> str:
    return f"0x{bits:04x} ({bits_to_float(bits):+.6g})"


def main() -> int:
    if EXT is None:
        raise SystemExit("build the pytorch extension first (pytorch/setup.py)")
    if len(sys.argv) > 1:
        so = Path(sys.argv[1])
    else:
        print("probe_h21: building the probe variant library ...")
        so = build_probe_library()
    print(f"probe_h21_convert_f8: kernel={so}")
    os.environ["GC_KERNEL_PATH"] = str(so.resolve())
    os.environ.setdefault("PT_HPU_LAZY_MODE", "0")

    import torch  # noqa: E402
    import habana_frameworks.torch.core  # noqa: F401, E402

    torch.ops.load_library(str(EXT))
    op = torch.ops.custom_op.custom_qwen4exp_nvfp4_indexed_dequant_bf16_gaudi2

    # N = len(FLAG_SETS) so the op's [S, N, K] output has one row per flag
    # combination; every row of the packed plane carries the same 256 bytes.
    rows = len(FLAG_SETS)
    scales = torch.zeros((1, rows, 32), dtype=torch.uint8, device="hpu")
    scale2 = torch.ones(1, dtype=torch.float32, device="hpu")
    ids = torch.zeros(1, dtype=torch.int32, device="hpu")

    def run(src_bytes: np.ndarray) -> np.ndarray:
        """One launch; returns int16 BF16 bits, shape [rows, 256] = v1 then v2."""
        packed = torch.from_numpy(
            np.ascontiguousarray(np.tile(src_bytes.reshape(1, 1, 256), (1, rows, 1)))
        ).to("hpu")
        res = op(ids, packed, scales, scale2)
        torch.hpu.synchronize()
        bits = res.view(torch.int16).cpu().numpy().reshape(len(FLAG_SETS), -1)
        assert bits.shape[1] >= 256, bits.shape
        return bits[:, :256]

    # ------------------------------------------------------------------
    # (a) lane mapping, one-hot per source byte index
    # ------------------------------------------------------------------
    print("\n(a) lane mapping: source byte b (0x38 = 1.0 one-hot) -> (half, lane)")
    lane_hits = np.zeros((len(FLAG_SETS), 256, 2), dtype=np.int64)  # [row, b, half]
    pos_of = np.full((len(FLAG_SETS), 256), -1, dtype=np.int64)     # 0..255
    for b in range(256):
        src = np.zeros(256, dtype=np.uint8)
        src[b] = 0x38
        got = run(src)
        for row in range(len(FLAG_SETS)):
            hits = np.flatnonzero(got[row] != 0)
            for pos in hits:
                lane_hits[row, b, pos // 128] += 1
                pos_of[row, b] = pos
            if hits.size != 1:
                print(f"    [warn] row {row} byte {b}: {hits.size} lanes lit "
                      f"({hits[:8].tolist()})")
    for row, (name, _) in enumerate(FLAG_SETS):
        v1 = [b for b in range(256) if lane_hits[row, b, 0]]
        v2 = [b for b in range(256) if lane_hits[row, b, 1]]
        print(f"\n  {name}")
        print(f"    pair.v1 <- {len(v1):3d} byte indices: "
              f"{v1[:6]} ... {v1[-3:] if v1 else []}")
        print(f"    pair.v2 <- {len(v2):3d} byte indices: "
              f"{v2[:6]} ... {v2[-3:] if v2 else []}")
        if len(v1) == 128 and v1 == list(range(128)):
            print("    model V1-'lo half': v1 lane i = byte i, v2 lane i = byte 128+i")
        elif len(v1) == 128 and v1 == list(range(0, 256, 2)):
            print("    model V1-'even/odd': v1 lane i = byte 2i, v2 lane i = byte 2i+1")
        else:
            print(f"    lane map (byte -> half/lane), first 12: "
                  f"{[(b, int(lane_hits[row, b, 1]), int(pos_of[row, b])) for b in range(12)]}")
        print(f"    v1 lane->byte: {v1[:16]}{' ...' if len(v1) > 16 else ''}")

    # ------------------------------------------------------------------
    # (b) all 128 codes 0x00..0x7F, bit for bit
    # ------------------------------------------------------------------
    print("\n(b) 0x00..0x7F through convert.f8_143 vs IEEE E4M3 reference")
    src = np.arange(256, dtype=np.uint8) & 0x7F   # byte b holds code b&0x7F
    got = run(src)
    ref = np.array([e4m3_bits(c) for c in range(0x80)], dtype=np.int16)
    val = np.array([e4m3_value(c) for c in range(0x80)], dtype=np.float64)
    for row, (name, _) in enumerate(FLAG_SETS):
        # read each code at the lane that carries byte c (lane map already known)
        ok_all, bad = 0, []
        for c in range(0x80):
            pos = pos_of[row, c]
            got_bits = int(got[row][pos]) & 0xFFFF
            if got_bits == (int(ref[c]) & 0xFFFF):
                ok_all += 1
            else:
                bad.append((c, got_bits, int(ref[c]) & 0xFFFF))
        print(f"\n  {name}: {ok_all}/128 codes bit-identical")
        groups = {
            "0x00 (+0)": [0x00],
            "subnormal 0x01..0x07": list(range(0x01, 0x08)),
            "normal 0x08..0x77": list(range(0x08, 0x78)),
            "exp=15 0x78..0x7E": list(range(0x78, 0x7F)),
            "NaN code 0x7F": [0x7F],
        }
        for label, codes in groups.items():
            n_ok = sum(1 for c in codes
                       if (int(got[row][pos_of[row, c]]) & 0xFFFF)
                       == (int(ref[c]) & 0xFFFF))
            print(f"    {label:22s} {n_ok:3d}/{len(codes):3d}")
        for c, g, r in bad[:10]:
            print(f"    code 0x{c:02x}: got {bits_to_str(g)} want {bits_to_str(r)} "
                  f"(exact {val[c]:.6g})")
        if len(bad) > 10:
            print(f"    ... {len(bad) - 10} more mismatches")
        # redundancy: bytes 128..255 carry the same codes, read them through v2
        dup_ok = 0
        for c in range(0x80):
            pos = pos_of[row, 128 + c]
            if pos < 0:
                continue
            dup_ok += int((int(got[row][pos]) & 0xFFFF) == (int(ref[c]) & 0xFFFF))
        print(f"    duplicate copy in bytes 128..255: {dup_ok}/128 identical")

    # ------------------------------------------------------------------
    # (c) the bias-shift fix: BIAS15 decodes every code to value/256, so one
    #     exact x256 (a BF16 multiply, or +0x0800 on the exponent bits) makes
    #     the whole 0x00..0x7F range bit-identical -- including exp=15.
    # ------------------------------------------------------------------
    print("\n(c) bias-shift fix: convert(BIAS15) * 256 vs the reference")
    for row, (name, _) in enumerate(FLAG_SETS):
        if "BIAS15" not in name and "BIAS11" not in name:
            continue
        shift = 8 if "BIAS15" in name else 4
        n_ok = 0
        bad = []
        for c in range(0x80):
            pos = pos_of[row, c]
            got_bits = int(got[row][pos]) & 0xFFFF
            # exact power-of-two rescale of the decoded value (what the kernel
            # does with v_bf16_mul_b(conv, 256.0f))
            scaled = np.float32(bits_to_float(got_bits)) * np.float32(2.0 ** shift)
            scaled_bf16 = int(np.float32(scaled).astype(np.float16).view(np.uint16)
                              ) if False else None
            want = bits_to_float(int(ref[c]) & 0xFFFF)
            if np.float32(scaled) == np.float32(want) and np.isfinite(scaled):
                n_ok += 1
            else:
                bad.append((c, got_bits, scaled, want))
        print(f"  {name}: value*2^{shift} == reference value for {n_ok}/128 codes")
        for c, g, sc, want in bad[:6]:
            print(f"    code 0x{c:02x}: {bits_to_str(g)} * 2^{shift} = {sc:.6g}, "
                  f"want {want:.6g}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
