"""H19 Step 3 — TPC GEMV inner-loop A/B on Gaudi2 (compile-gate companion).

Times the indexed NVFP4 GEMV / fused SwiGLU GEMV of the *loaded* kernel library
and, with ``--out``, dumps every output as BF16 so two builds can be compared
bit for bit (``--compare``). This is the device half of the Step 3 audit; the
static half is the ``tpc-clang -O2 -march=gaudi2 -S`` bundle/instruction count
of the same variants.

Variants under test (generated by a throwaway script that is not kept):

  base  production: mov_dg + shuffle.u8 + shr + and  per 128-element part
  tail  production with the trailing ``and 15`` dropped (ROM lookup 457 masks
        the index to 4 bits) -> 3 ops per part, `and.u16` -32 per tile
  swz   pre-swizzled packed plane (4x4 transpose of the 16-byte blocks inside
        every 256-byte tile) + one two-source shuffle per part; the tile-level
        ``and``/``shr`` cover all 512 nibbles in 2 instructions

``--swizzle`` feeds the swizzled plane the ``swz`` kernel expects; the plane is
produced from the same bytes, so ``base`` (unswizzled) and ``swz`` (swizzled)
must agree bit for bit on identical weights.

Run (card must be free):
  PT_HPU_LAZY_MODE=0 python3 tools/qwen4exp_flashnext/bench_h19_tpc.py \
      --kernel vllm-gaudi/csrc/qwen4exp/build/libqwen4exp_gaudi2_kernels.so \
      --label base --out /tmp/h19/base.npz
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
KERNEL = REPO / "vllm-gaudi/csrc/qwen4exp/build/libqwen4exp_gaudi2_kernels.so"
EXT = next((REPO / "vllm-gaudi/csrc/qwen4exp/pytorch").glob(
    "hpu_qwen4exp_nvfp4_dequant_pt2*.so"), None)
os.environ.setdefault("PT_HPU_LAZY_MODE", "0")

import numpy as np  # noqa: E402

EXPERTS = 512
GATE_UP = dict(n=640, k=2560)
DOWN = dict(n=2560, k=640)
SLOTS = (10, 40)


def make_planes(rng, experts, n, k, swizzle):
    packed = rng.integers(0, 256, size=(experts, n, k // 2), dtype=np.uint8)
    scales = rng.integers(0, 256, size=(experts, n, k // 16), dtype=np.uint8)
    bad = (scales & 0x7F) == 0x7F
    scales = np.where(bad, scales & 0x7E, scales).astype(np.uint8)
    scale2 = (rng.random(experts, dtype=np.float32) * 1e-4 + 1e-5).astype(np.float32)
    if swizzle:
        swizzled = swizzle_plane(packed)
        if swizzled is None:
            print(f"  [skip-swizzle] K/2={packed.shape[-1]} is not a multiple of 256")
        else:
            packed = swizzled
    return packed, scales, scale2


def swizzle_plane(packed: np.ndarray) -> np.ndarray:
    """new[g*64 + 16p + c] = old[64p + 16g + c] inside every 256-byte tile.

    A 4x4 transpose of the 16-byte blocks: one part's 64 bytes end up spread
    over the four dual groups (16 bytes each), which is what lets a single
    v_u8_shuffle_b read a part without v_u8_mov_dual_group_all_b.
    """
    e, n, half = packed.shape
    if half % 256:
        return None  # ragged last tile: the swizzle cannot apply (see the report)
    t = packed.reshape(e, n, half // 256, 4, 4, 16)
    return np.ascontiguousarray(t.swapaxes(3, 4)).reshape(e, n, half)


def _consume(tensor):
    return tensor.float().sum().item()


def _bench(fn, iters, samples):
    fn(0)
    _consume(fn(0))
    times = []
    import torch

    for _ in range(samples):
        t0 = time.perf_counter()
        for i in range(iters):
            fn(i)
        torch.hpu.synchronize()
        times.append((time.perf_counter() - t0) / iters * 1e3)
    return statistics.median(times)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--kernel", type=Path, default=KERNEL)
    ap.add_argument("--label", default="run")
    ap.add_argument("--out", type=Path, default=None, help="write outputs for a bit compare")
    ap.add_argument("--compare", type=Path, nargs=2, default=None,
                    help="two .npz dumps: report bit differences")
    ap.add_argument("--swizzle", action="store_true", help="feed the swizzled packed plane")
    ap.add_argument("--json", type=Path, default=None)
    ap.add_argument("--slots", default=",".join(str(s) for s in SLOTS))
    args = ap.parse_args()

    if args.compare:
        a = np.load(args.compare[0])
        b = np.load(args.compare[1])
        print(f"compare {args.compare[0]} vs {args.compare[1]}")
        ok = True
        for key in sorted(set(a.files) & set(b.files)):
            x, y = a[key], b[key]
            if x.shape != y.shape:
                print(f"  {key:14s} shape {x.shape} != {y.shape}  MISSING")
                ok = False
                continue
            diff = int((x != y).sum())
            rel = float(np.abs(x.astype(np.float32) - y.astype(np.float32)).max()) if diff else 0.0
            print(f"  {key:14s} differing {diff:>9}  max|d| {rel:.3e}  "
                  f"n {x.size}")
            ok = ok and diff == 0
        print("  BIT IDENTICAL" if ok else "  DIVERGED")
        return 0 if ok else 1

    if not args.kernel.is_file():
        raise SystemExit(f"kernel database missing: {args.kernel}")
    os.environ["GC_KERNEL_PATH"] = str(args.kernel.resolve())
    if EXT is None:
        raise SystemExit("build the pytorch extension first")

    import torch
    import habana_frameworks.torch.core  # noqa: F401

    torch.ops.load_library(str(EXT))
    gemv = torch.ops.custom_op.custom_qwen4exp_nvfp4_indexed_gemv_bf16_gaudi2
    swiglu = getattr(torch.ops.custom_op,
                     "custom_qwen4exp_nvfp4_indexed_swiglu_gemv_bf16_gaudi2", None)

    rng = np.random.default_rng(20261105)
    print(f"bench_h19_tpc: kernel={args.kernel} label={args.label} "
          f"swizzle={args.swizzle} eager")

    def to_hpu(packed, scales, scale2):
        return (torch.from_numpy(packed).to("hpu"),
                torch.from_numpy(scales).to("hpu"),
                torch.from_numpy(scale2).to("hpu"))

    planes = {}
    for kind, geom in (("gate", GATE_UP), ("up", GATE_UP), ("down", DOWN)):
        packed, scales, scale2 = make_planes(rng, EXPERTS, geom["n"], geom["k"],
                                             args.swizzle)
        planes[kind] = to_hpu(packed, scales, scale2)
    gib = sum(t.numel() * t.element_size() for plane in planes.values() for t in plane) / 2**30
    print(f"  device planes: {gib:.2f} GiB")

    out = {}
    rows = []

    for slots in [int(s) for s in args.slots.split(",") if s.strip()]:
        ids = torch.from_numpy(rng.integers(0, EXPERTS, size=slots, dtype=np.int32)).to("hpu")
        # From the seeded numpy RNG, not torch's global one: two builds must see
        # byte-identical activations for the --compare gate to mean anything.
        x_gate = torch.from_numpy(
            rng.standard_normal((slots, GATE_UP["k"]), dtype=np.float32)
        ).to(torch.bfloat16).to("hpu")
        x_down = torch.from_numpy(
            rng.standard_normal((slots, DOWN["k"]), dtype=np.float32)
        ).to(torch.bfloat16).to("hpu")
        wanted = [("gate", GATE_UP, x_gate), ("down", DOWN, x_down)]
        if args.swizzle:
            # only the complete-tile shapes can carry the swizzled plane
            wanted = [w for w in wanted if w[1]["k"] // 2 % 256 == 0]
        for kind, geom, act in wanted:
            p, s, s2 = planes[kind]
            ms = _bench(lambda i, p=p, s=s, s2=s2, a=act: gemv(ids, p, s, a, s2),
                        iters=20, samples=7)
            rows.append(dict(label=args.label, op=f"gemv_{kind}", slots=slots, ms=ms))
            print(f"  gemv_{kind:5s} S={slots:<3d} {ms:8.4f} ms")
            if args.out is not None:
                out[f"gemv_{kind}_s{slots}"] = gemv(ids, p, s, act, s2).cpu().float().numpy()
        # fused SwiGLU GEMV vs the two standalone projections it replaces
        gp, gs, gs2 = planes["gate"]
        up_p, us, us2 = planes["up"]
        if swiglu is not None:
            ms = _bench(lambda i: swiglu(ids, gp, gs, gs2, up_p, us, us2, x_gate),
                        iters=20, samples=7)
            rows.append(dict(label=args.label, op="swiglu_gemv", slots=slots, ms=ms))
            print(f"  swiglu_gemv  S={slots:<3d} {ms:8.4f} ms")
            if args.out is not None:
                out[f"swiglu_s{slots}"] = swiglu(ids, gp, gs, gs2, up_p, us, us2,
                                                 x_gate).cpu().float().numpy()

        def two_gemv(i):
            g = gemv(ids, gp, gs, x_gate, gs2)
            u = gemv(ids, up_p, us, x_gate, us2)
            return torch.nn.functional.silu(g) * u

        ms = _bench(two_gemv, iters=20, samples=7)
        rows.append(dict(label=args.label, op="2x_gemv_silu_mul", slots=slots, ms=ms))
        print(f"  2x_gemv+silu S={slots:<3d} {ms:8.4f} ms")

    if args.out is not None:
        np.savez(args.out, **out)
        print(f"wrote {args.out} ({len(out)} tensors)")
    if args.json:
        args.json.write_text(json.dumps(rows, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
