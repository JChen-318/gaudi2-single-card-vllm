"""Convert the fixed GEMM128 text fixture to a single-master register template.

The text dump omits RATE_LIMITER. Its nonzero value comes from the separately
recorded register observation, NOT from filling missing fields with zeros.
This generator intentionally rejects shapes other than the verified fixture.
"""
import argparse
import json
import re
from pathlib import Path


def generate(text: str, runtime: dict) -> str:
    if "validElements: [128, 16384, 16384, 16384, 16384]" not in text:
        raise ValueError("Only the verified GEMM128 fixture is supported")
    regs = dict.fromkeys(range(8, 0x2E0, 4), 0)
    sections = [
        ("Brains:", "Header:", 0x28, 2),
        ("Header:", "Ctrl:", 0x30, 2),
        ("Ctrl:", "Tensor: tensorA", 0x38, 2),
        ("Tensor: tensorA", "Tensor: tensorB", 0x40, 22),
        ("Tensor: tensorB", "Tensor: tensorCout", 0x98, 22),
        ("Tensor: tensorCout", "SyncObject:", 0xF0, 22),
        ("SyncObject:", "AguIn:", 0x148, 5),
    ]
    for start, end, offset, count in sections:
        block = text.split(start, 1)[1].split(end, 1)[0]
        values = re.findall(r"dw\[(\d+)\]\s*:\s*(0x[0-9a-f]+)", block)
        if [int(index) for index, _ in values] != list(range(count)):
            raise ValueError(f"Incomplete or unexpected {start} block")
        for index, value in values:
            regs[offset + int(index) * 4] = int(value, 16)

    for tag, base, count in [("aguIn", 0x15C, 5), ("aguOut", 0x22C, 2)]:
        entries = re.findall(tag + r"\[(\d+)\]\[(MASTER|SLAVE)\]: \[([^\]]+)\]", text)
        if {(int(i), side) for i, side, _ in entries} != {
            (i, side) for i in range(count) for side in ["MASTER", "SLAVE"]
        } or len(entries) != count * 2:
            raise ValueError(f"Incomplete or duplicate {tag} entries")
        for index, side, array in entries:
            values = [int(x.strip()) for x in array.split(",")]
            if len(values) != 5:
                raise ValueError("An AGU entry must have five offsets")
            for j, value in enumerate(values):
                regs[base + int(index) * 40 + (20 if side == "SLAVE" else 0) + j * 4] = value & 0xFFFFFFFF

    for field, offset in [("A", 0x224), ("B", 0x228), ("Cout", 0x27C)]:
        regs[offset] = int(re.search("spatialSizeMinus1" + field + r" : (0x\w+)", text)[1], 16)
    conv = text.split("Conv:", 1)[1].split("OuterLoop:", 1)[0]
    regs[0x280] = int(re.search(r"dw\[0\]: (0x\w+)", conv)[1], 16)
    halves = [int(value, 16) for _, value in re.findall(r"w\[([1-4])\]: (0x\w+)", conv)]
    if len(halves) != 4 or any(value > 0xFFFF for value in halves):
        raise ValueError("Invalid convolution association words")
    regs[0x284] = halves[0] | (halves[1] << 16)
    regs[0x288] = halves[2] | (halves[3] << 16)
    outer = text.split("OuterLoop:", 1)[1].split("numIterationsMinus1", 1)[0]
    regs[0x28C] = int(re.search(r"dw: (0x\w+)", outer)[1], 16)
    regs[0x290] = int(re.search(r"numIterationsMinus1 : (0x\w+)", text)[1], 16)
    repeat = text.split("SBRepeat:", 1)[1].split("Fp8Bias:", 1)[0]
    regs[0x294] = int(re.search(r"dw: (0x\w+)", repeat)[1], 16)
    # Bias/user-data/PCU/padding/performance fields are zero for this fixture.
    # Confirm the observed rate-control setting before creating a runnable header.
    if runtime.get("0x29c") != 0x040404:
        raise ValueError("Missing or unexpected observed RATE_LIMITER setting")
    regs[0x29C] = runtime["0x29c"]
    # The fixture's slave/batch lanes are outside its 128x128 output. Disable
    # slave brains and the master<->slave handshake for this one-master path.
    regs[0x28] &= ~0x80808080
    regs[0x2C] &= ~0x808080
    regs[0x148] &= ~(3 << 15)
    header = "/* Generated by generate_desc.py from GEMM128 fixture + register evidence. */\n"
    header += "static const uint32_t desc_words[182] = {\n"
    header += "\n".join(f"    0x{regs[i]:08x}, /* 0xb{i:03x} */" for i in range(8, 0x2E0, 4))
    return header + "\n};\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fixture", type=Path)
    parser.add_argument("--runtime-registers", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.fixture.read_text(encoding="utf-8-sig"),
                                   json.loads(args.runtime_registers.read_text(encoding="utf-8-sig"))),
                           encoding="utf-8", newline="\n")
